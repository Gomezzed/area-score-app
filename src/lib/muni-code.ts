// ============================================================
// 全国地方公共団体コード（6桁）への正規化ユーティリティ。
//
//   背景（CLAUDE.md 原則2 / コード体系ズレ）:
//     - public.municipalities.city_code … 5桁 JIS（例: 岩国 35208）
//     - town_monthly_metrics.muni_code   … 6桁（例: 岩国 352080）
//   6桁目はゼロ埋めではなく、JIS X 0402 の「検査数字（チェックディジット）」。
//   したがって 5→6 桁は必ず検査数字を算出して付与する（`code + '0'` は誤り）。
//
//   検査数字の算出（JIS X 0402）:
//     1. 5桁の各位に、左から重み 6,5,4,3,2 を乗じる。
//     2. 積の総和 Σ を求める。
//     3. 余り r = Σ mod 11 を求める。
//     4. 検査数字 = (11 - r) mod 10。
//        （11-r が 10/11 になる r=1/0 のとき、1の位を採って 0/1 とする挙動を mod 10 で表現）
//
//   実測突合済（このリポジトリの正データ / 本番DB と一致）:
//     35208 → 352080（岩国）, 28214 → 282146（宝塚）,
//     46201 → 462012（鹿児島）, 28100 → 281000（神戸市）。
//
//   ※ データ投入側（姉妹repo area-score-data）は 6桁を直接保持しており、
//     5→6 桁の独立変換実装は持たない。本関数が唯一の変換点となる。
// ============================================================

// 5桁 JIS コードに付与する検査数字（0-9）を算出する。
function checkDigit5(code5: string): number {
  const weights = [6, 5, 4, 3, 2]
  let sum = 0
  for (let i = 0; i < 5; i++) {
    sum += Number(code5[i]) * weights[i]
  }
  return (11 - (sum % 11)) % 10
}

// 市区町村コードを 6桁の全国地方公共団体コードへ正規化する純粋関数。
//   - 6桁数字 … そのまま返す（冪等。既に正データを受け取っても壊さない）。
//   - 5桁数字 … JIS X 0402 の検査数字を付与して 6桁化。
//   - それ以外（null/空/桁数違い/非数字）… null（＝対応不能。呼び出し側で「準備中」扱い）。
export function toMuniCode6(code: string | number | null | undefined): string | null {
  if (code == null) return null
  const s = String(code).trim()
  if (/^\d{6}$/.test(s)) return s
  if (!/^\d{5}$/.test(s)) return null
  return s + String(checkDigit5(s))
}
