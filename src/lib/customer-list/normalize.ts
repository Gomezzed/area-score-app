// ============================================================
// 住所文字列の正規化（React 非依存の純ロジック）。
//   突合エンジンの前処理。表記ゆれを吸収し「町域名で照合できる」形に整える。
//
//   吸収する主な揺れ:
//     - 全角/半角（英数記号は NFKC で半角化。丁目の全角数字も算用数字化）
//     - 旧字体 → 新字体（住所頻出のみ・保守的な最小マップ）
//     - ハイフン各種（‐ ‑ – — ― ー − 等）→ 半角 '-'
//     - 「大字」「字」の除去（町域名の直前に付く接頭辞）
//     - 空白（全角/半角）の除去
//
//   ⚠ 原則1/5: 正規化は「表記ゆれの吸収」までに留め、推測での補完はしない。
//     町丁目・番地・号は除去せず残す（町域名の抽出は match.ts が prefix で行う）。
// ============================================================

// 旧字体 → 新字体（住所・地名で実際に出現しうるものに限定した保守的マップ）。
//   むやみに広げると誤変換のリスク。既知の頻出のみ。
const KYUJITAI_MAP: Record<string, string> = {
  澤: '沢',
  齋: '斎',
  齊: '斎',
  邊: '辺',
  邉: '辺',
  龍: '竜',
  髙: '高',
  﨑: '崎',
  嵜: '崎',
  圓: '円',
  檜: '桧',
  濱: '浜',
  濵: '浜',
  舘: '館',
  廣: '広',
  惠: '恵',
  槇: '槙',
  國: '国',
  區: '区',
  會: '会',
  應: '応',
  櫻: '桜',
  萬: '万',
  峯: '峰',
  茨: '茨',
}

// ハイフン・長音・ダッシュ類（住所の番地区切り）→ 半角 '-' に統一。
const HYPHEN_VARIANTS = /[‐‑‒–—―ー−﹣－ｰ]/g

// 全角空白・半角空白・タブ等。
const WHITESPACE = /[\s　]+/g

// 旧字体を新字体へ置換する。
function normalizeKyujitai(s: string): string {
  let out = ''
  for (const ch of s) {
    out += KYUJITAI_MAP[ch] ?? ch
  }
  return out
}

// 住所文字列を突合用に正規化する純粋関数。
//   入力が null/空なら空文字を返す（呼び出し側は out_of_scope として扱える）。
export function normalizeAddress(input: string | null | undefined): string {
  if (input == null) return ''
  // 1. Unicode 正規化（NFKC）: 全角英数記号→半角、全角数字→算用数字、
  //    互換文字（㈱ 等）や全角括弧も正規形へ。
  let s = input.normalize('NFKC')
  // 2. 旧字体→新字体
  s = normalizeKyujitai(s)
  // 3. ハイフン類を半角 '-' に統一
  s = s.replace(HYPHEN_VARIANTS, '-')
  // 4. 「大字」「字」接頭辞の除去（町域名の直前に付くもの）。
  //    "大字○○" / "字○○" を "○○" に。地名の一部としての「字」までは触らない
  //    ため、行頭または非文字境界の後ろに限定せず、素直に接頭辞トークンとして除去。
  s = s.replace(/大字/g, '').replace(/(?<![0-9-])字/g, '')
  // 5. 空白の除去
  s = s.replace(WHITESPACE, '')
  // 6. 連続ハイフンの圧縮（"1--2" → "1-2"）
  s = s.replace(/-{2,}/g, '-')
  return s.trim()
}

// 町域名の照合キーを作る（町名側の正規化）。
//   住所と同じ正規化を通したうえで、比較を安定させる。
export function normalizeTownName(input: string | null | undefined): string {
  return normalizeAddress(input)
}
